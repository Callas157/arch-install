#!/usr/bin/python3
"""Provision internal data disks ONLY during a new Callas OS installation.

Never partition, format, reset a UUID, fix NTFS, or recursively change ownership.
A serious filesystem error remains a diagnostic, not permission to destroy data.
"""
import os
from pathlib import Path
import pwd
import re
import stat
import subprocess
import sys
import tempfile

FSTAB = Path('/etc/fstab')
AUTOMOUNT = '/usr/local/libexec/callas-automount'
MARKER = '# Montagem de discos de dados — Callas OS'
UUID = re.compile(r'[0-9A-Fa-f]+(?:-[0-9A-Fa-f]+)*\Z')
OS_ROOT_NAMES = {'etc', 'usr', 'var', 'boot', 'root', 'home', 'opt', 'sys', 'proc', 'dev', 'run'}
# The optional data volume is wanted but not ordered before local-fs.target
# when mounted with nofail. Explicit ordering keeps Steam from seeing an
# empty mountpoint during login, without making a missing disk break boot.
BEFORE_LOCAL_FS = 'x-systemd.before=local-fs.target'
VALID_DATA_FS = {'ext4', 'ntfs3', 'exfat', 'ext2', 'ext3', 'xfs', 'btrfs'}


def candidates(text):
    """Only touch ext4 data rows generated by the verified automount helper."""
    seen_marker = False
    result = []
    for line in text.splitlines():
        if line == MARKER:
            seen_marker = True
            continue
        if not seen_marker or not line or line.lstrip().startswith('#'):
            continue
        cells = line.split()
        if len(cells) != 6 or cells[2] != 'ext4' or not cells[0].startswith('UUID='):
            continue
        uuid = cells[0][5:]
        if (not UUID.fullmatch(uuid) or cells[1] != '/mnt/callas-' + uuid.lower()
                or cells[4] != '0' or cells[5] not in ('0', '2')):
            continue
        options = cells[3].split(',')
        if not {'nosuid', 'nodev', 'nofail'} <= set(options) or 'noauto' in options:
            continue
        result.append((cells[1], uuid))
    return result


def prepare_fstab(text):
    """Order existing Callas data mounts before login; enable ext4 boot fsck.

    Only rewrite rows in the original Callas marker section with an expected
    UUID-based /mnt/callas-... target; never alter the system/root fstab rows.
    """
    lines = []
    marked = False
    for line in text.splitlines(keepends=True):
        if line.rstrip('\n') == MARKER:
            marked = True
            lines.append(line)
            continue
        if not marked or not line.strip() or line.lstrip().startswith('#'):
            lines.append(line)
            continue
        cells = line.split()
        if len(cells) != 6 or cells[2] not in VALID_DATA_FS or not cells[0].startswith('UUID='):
            lines.append(line)
            continue
        uuid = cells[0][5:]
        if (not UUID.fullmatch(uuid) or cells[1] != '/mnt/callas-' + uuid.lower()
                or cells[4] != '0' or cells[5] not in ('0', '2')):
            lines.append(line)
            continue
        options = cells[3].split(',')
        if not {'nosuid', 'nodev', 'nofail'} <= set(options) or 'noauto' in options:
            lines.append(line)
            continue
        if BEFORE_LOCAL_FS not in options:
            options.append(BEFORE_LOCAL_FS)
        if cells[2] == 'ext4':
            if 'errors=remount-ro' not in options:
                options.append('errors=remount-ro')
            cells[5] = '2'  # systemd-fsck handles journal recovery at boot
        cells[3] = ','.join(options)
        ending = '\n' if line.endswith('\n') else ''
        lines.append('\t'.join(cells) + ending)
    return ''.join(lines)


def atomic_fstab(contents):
    current = FSTAB.lstat()
    if not stat.S_ISREG(current.st_mode) or current.st_uid != 0 or current.st_mode & 0o022:
        raise RuntimeError('fstab não é um arquivo regular protegido; configuração interrompida')
    previous = FSTAB.read_text(encoding='utf-8')
    if contents == previous:
        return
    with tempfile.NamedTemporaryFile(mode='w', encoding='utf-8', dir=FSTAB.parent,
                                     prefix='.fstab.callas-storage-', delete=False) as file:
        staged = Path(file.name)
        try:
            os.fchown(file.fileno(), current.st_uid, current.st_gid)
            os.fchmod(file.fileno(), stat.S_IMODE(current.st_mode))
            file.write(contents)
            file.flush()
            os.fsync(file.fileno())
            verify = subprocess.run(['findmnt', '--verify', '--tab-file', str(staged)],
                                    capture_output=True, text=True, env={**os.environ, 'LC_ALL': 'C'})
            if verify.returncode:
                original = subprocess.run(['findmnt', '--verify', '--tab-file', str(FSTAB)],
                                          capture_output=True, text=True,
                                          env={**os.environ, 'LC_ALL': 'C'})
                if not (original.returncode == verify.returncode
                        and original.stdout == verify.stdout and original.stderr == verify.stderr
                        and '0 parse errors,' in original.stderr):
                    raise RuntimeError('a verificação da tabela de montagem falhou: '
                                       + verify.stderr.strip())
            changed = FSTAB.lstat()
            if (changed.st_ino, changed.st_dev, changed.st_ctime_ns) != (current.st_ino, current.st_dev, current.st_ctime_ns) or FSTAB.read_text(encoding='utf-8') != previous:
                raise RuntimeError('fstab foi alterado simultaneamente; nada substituído')
            os.replace(staged, FSTAB)
            directory = os.open(FSTAB.parent, os.O_RDONLY | os.O_DIRECTORY)
            try:
                os.fsync(directory)
            finally:
                os.close(directory)
        finally:
            staged.unlink(missing_ok=True)


def prepare_access(target, account):
    """Change only an ext4 volume's top-level owner, not the user's files."""
    path = Path(target)
    if path.is_symlink() or not path.is_mount():
        raise RuntimeError('o destino não é um ponto de montagem seguro: ' + target)
    names = {entry.name for entry in path.iterdir()}
    if names & OS_ROOT_NAMES:
        print('Armazenamento: disco contém estrutura de sistema; permissões preservadas em ' + target)
        return
    info = path.stat()
    if info.st_uid == 0:
        os.chown(path, account.pw_uid, account.pw_gid)
        print('Armazenamento: acesso do usuário configurado em ' + target)
    elif info.st_uid != account.pw_uid:
        print('Armazenamento: dono anterior preservado em ' + target + '; arquivos não foram alterados.')


def main(username):
    if os.geteuid() != 0:
        raise RuntimeError('esta configuração requer root durante a instalação limpa')
    account = pwd.getpwnam(username)
    if not account.pw_uid:
        raise RuntimeError('não é permitido configurar o volume para root')
    subprocess.run([AUTOMOUNT, username], check=True)
    original = FSTAB.read_text(encoding='utf-8')
    entries = candidates(original)
    atomic_fstab(prepare_fstab(original))
    if not entries:
        print('Armazenamento: nenhuma nova partição interna ext4 elegível; outros formatos ficam preservados.')
        return
    for target, uuid in entries:
        print('Armazenamento: ext4 por UUID ' + uuid + ', checagem segura após interrupções.')
        path = Path(target)
        if path.is_symlink() or path.is_mount():
            print('Armazenamento: volume já montado ou caminho inseguro; sem troca de permissões: ' + target)
            continue
        mounted = subprocess.run(['mount', '--', target], capture_output=True, text=True)
        if mounted.returncode:
            print('Armazenamento: não foi possível montar ' + target + ': '
                  + mounted.stderr.strip() + '; dados preservados, sem formatação.', file=sys.stderr)
            continue
        try:
            prepare_access(target, account)
        except (OSError, RuntimeError) as error:
            print('Armazenamento: acesso mantido sem alterações em ' + target + ': ' + str(error), file=sys.stderr)
        finally:
            result = subprocess.run(['umount', '--', target], capture_output=True, text=True)
            if result.returncode:
                print('Armazenamento: aviso ao desmontar ' + target + ': ' + result.stderr.strip(), file=sys.stderr)
    print('Armazenamento: volumes por UUID no fstab, montagem no boot e sem senha; discos ausentes não impedem inicialização.')


if __name__ == '__main__':
    if len(sys.argv) != 2:
        raise SystemExit('Uso interno: callas-storage-setup USUARIO')
    try:
        main(sys.argv[1])
    except (OSError, ValueError, RuntimeError, subprocess.CalledProcessError) as error:
        print('Armazenamento: configuração inicial interrompida: ' + str(error), file=sys.stderr)
        raise SystemExit(1)
