#!/usr/bin/python3
"""Provision internal data disks ONLY during a new Callas OS installation.

Never partition, format, reset a UUID, fix NTFS, or recursively change ownership.
A serious filesystem error remains a diagnostic, not permission to destroy data.
"""
import os
from pathlib import Path
import pwd
import re
import subprocess
import sys

FSTAB = Path('/etc/fstab')
AUTOMOUNT = '/usr/local/libexec/callas-automount'
MARKER = '# Montagem de discos de dados — Callas OS'
UUID = re.compile(r'[0-9A-Fa-f]+(?:-[0-9A-Fa-f]+)*\Z')
OS_ROOT_NAMES = {'etc', 'usr', 'var', 'boot', 'root', 'home', 'opt', 'sys', 'proc', 'dev', 'run'}
def candidates(text):
    """Only touch ext4 data rows generated by the verified automount helper."""
    seen_marker = False
    result = []
    for line in text.splitlines():
        if line == MARKER:
            seen_marker = True
            continue
        if not seen_marker or not line or line.lstrip().startswith('#'):
            continue
        cells = line.split()
        if len(cells) != 6 or cells[2] != 'ext4' or not cells[0].startswith('UUID='):
            continue
        uuid = cells[0][5:]
        if (not UUID.fullmatch(uuid) or cells[1] != '/mnt/callas-' + uuid.lower()
                or cells[4] != '0' or cells[5] not in ('0', '2')):
            continue
        options = cells[3].split(',')
        if not {'nosuid', 'nodev', 'nofail'} <= set(options) or 'noauto' in options:
            continue
        result.append((cells[1], uuid))
    return result


def prepare_access(target, account):
    """Change only an ext4 volume's top-level owner, not the user's files."""
    path = Path(target)
    if path.is_symlink() or not path.is_mount():
        raise RuntimeError('o destino não é um ponto de montagem seguro: ' + target)
    names = {entry.name for entry in path.iterdir()}
    if names & OS_ROOT_NAMES:
        print('Armazenamento: disco contém estrutura de sistema; permissões preservadas em ' + target)
        return
    info = path.stat()
    if info.st_uid == 0:
        os.chown(path, account.pw_uid, account.pw_gid)
        print('Armazenamento: acesso do usuário configurado em ' + target)
    elif info.st_uid != account.pw_uid:
        print('Armazenamento: dono anterior preservado em ' + target + '; arquivos não foram alterados.')


def main(username, formatted=()):
    if os.geteuid() != 0:
        raise RuntimeError('esta configuração requer root durante a instalação limpa')
    account = pwd.getpwnam(username)
    if not account.pw_uid:
        raise RuntimeError('não é permitido configurar o volume para root')
    subprocess.run([AUTOMOUNT, username], check=True)
    original = FSTAB.read_text(encoding='utf-8')
    entries = [(target, uuid) for target, uuid in candidates(original) if uuid in formatted]
    if not entries:
        print('Armazenamento: permissões dos volumes preservados permanecem como estavam.')
        return
    for target, uuid in entries:
        print('Armazenamento: ext4 por UUID ' + uuid + ', checagem segura após interrupções.')
        path = Path(target)
        if path.is_symlink() or path.is_mount():
            print('Armazenamento: volume já montado ou caminho inseguro; sem troca de permissões: ' + target)
            continue
        mounted = subprocess.run(['mount', '--', target], capture_output=True, text=True)
        if mounted.returncode:
            print('Armazenamento: não foi possível montar ' + target + ': '
                  + mounted.stderr.strip() + '; dados preservados, sem formatação.', file=sys.stderr)
            continue
        try:
            prepare_access(target, account)
        except (OSError, RuntimeError) as error:
            print('Armazenamento: acesso mantido sem alterações em ' + target + ': ' + str(error), file=sys.stderr)
        finally:
            result = subprocess.run(['umount', '--', target], capture_output=True, text=True)
            if result.returncode:
                print('Armazenamento: aviso ao desmontar ' + target + ': ' + result.stderr.strip(), file=sys.stderr)
    print('Armazenamento: volumes por UUID no fstab, montagem no boot e sem senha; discos ausentes não impedem inicialização.')


if __name__ == '__main__':
    if len(sys.argv) < 2:
        raise SystemExit('Uso interno: callas-storage-setup USUARIO [UUID_FORMATADO ...]')
    try:
        main(sys.argv[1], sys.argv[2:])
    except (OSError, ValueError, RuntimeError, subprocess.CalledProcessError) as error:
        print('Armazenamento: configuração inicial interrompida: ' + str(error), file=sys.stderr)
        raise SystemExit(1)
